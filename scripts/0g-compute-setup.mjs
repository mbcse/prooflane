#!/usr/bin/env node
/**
 * Automates the 0G Compute quickstart (testnet) flow:
 * https://build.0g.ai/compute/#quickstart
 *
 * Prereqs in repo root `.env`:
 *   - OG_COMPUTE_PRIVATE_KEY or ZERO_G_STORAGE_PRIVATE_KEY (0x… funded wallet)
 *   - ZG_RPC_ENDPOINT optional (default: https://evmrpc-testnet.0g.ai)
 *
 * The official quickstart deposits **3 OG** into the compute ledger before inference.
 * If you only have **0.1 OG**, `deposit` will fail until you add more from https://faucet.0g.ai
 *
 * Ongoing inference charges **unsettled fees** on your locked balance. If the API returns
 * `insufficient balance` / `required minimum is X` (often slightly above 1 OG after fees), run:
 *   0g-compute-cli transfer-fund --provider <provider> --amount <amount> --service inference
 * or bump `OG_COMPUTE_TRANSFER_AMOUNT` in `.env` and re-run this script (without --only-secret)
 * so more OG moves to the provider for inference.
 *
 * Usage:
 *   npm run 0g:compute-setup
 *   npm run 0g:compute-setup -- --only-secret   # re-run get-secret only (ledger already set up)
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import dotenv from "dotenv";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

for (const p of [join(ROOT, ".env"), join(ROOT, ".env.local")]) {
  if (existsSync(p)) dotenv.config({ path: p });
}

const onlySecret = process.argv.includes("--only-secret");

const ZG_RPC_ENDPOINT =
  process.env.ZG_RPC_ENDPOINT ||
  process.env.ZERO_G_EVM_RPC ||
  "https://evmrpc-testnet.0g.ai";

const rawPk =
  process.env.OG_COMPUTE_PRIVATE_KEY ||
  process.env.ZERO_G_STORAGE_PRIVATE_KEY ||
  process.env.PRIVATE_KEY;

if (!rawPk) {
  console.error(
    "Missing private key. Set OG_COMPUTE_PRIVATE_KEY or ZERO_G_STORAGE_PRIVATE_KEY in .env",
  );
  process.exit(1);
}

const formattedPk = rawPk.startsWith("0x") ? rawPk : `0x${rawPk}`;

const CLI = join(ROOT, "node_modules", ".bin", "0g-compute-cli");
if (!existsSync(CLI)) {
  console.error("0g-compute-cli not found. Run: npm install (root has @0gfoundation/0g-compute-ts-sdk)");
  process.exit(1);
}

const provider =
  process.env.OG_COMPUTE_PROVIDER ||
  "0xa48f01287233509FD694a22Bf840225062E67836";

const depositAmount = process.env.OG_COMPUTE_DEPOSIT_AMOUNT ?? "3";
const transferAmount = process.env.OG_COMPUTE_TRANSFER_AMOUNT ?? "1";

function runCli(args, { capture = false } = {}) {
  const env = {
    ...process.env,
    ZG_RPC_ENDPOINT,
    // CLI reads private key from ~/.0g-compute-cli/config.json only
  };
  console.log(`\n$ 0g-compute-cli ${args.join(" ")}\n`);
  if (capture) {
    return execFileSync(CLI, args, { encoding: "utf8", env });
  }
  execFileSync(CLI, args, { stdio: "inherit", env });
  return "";
}

/** Non-interactive equivalent of `login` — CLI stores key in ~/.0g-compute-cli/config.json */
function bootstrapCliConfig() {
  const dir = join(homedir(), ".0g-compute-cli");
  mkdirSync(dir, { recursive: true });
  const configPath = join(dir, "config.json");
  let cfg = {};
  try {
    cfg = JSON.parse(readFileSync(configPath, "utf8"));
  } catch {
    /* empty */
  }
  cfg.rpcEndpoint = ZG_RPC_ENDPOINT;
  cfg.network = "testnet";
  cfg.privateKey = formattedPk;
  cfg.lastUpdated = new Date().toISOString();
  writeFileSync(configPath, JSON.stringify(cfg, null, 2));
  console.log(`\n✓ Wrote ${configPath} (testnet RPC + private key for 0g-compute-cli)\n`);
}

function stripAnsi(s) {
  return s.replace(/\u001b\[[0-9;]*m/g, "");
}

function parseGetSecretOutput(out) {
  const text = stripAnsi(out);
  const bearer =
    text.match(/Authorization:\s*Bearer\s+(\S+)/)?.[1] ??
    text.match(/Bearer\s+(app-sk-[^\s]+)/)?.[1];
  const serviceUrl = text.match(/curl\s+(https?:\/\/[^\s]+)\/v1\/proxy/)?.[1];
  const modelMatch = text.match(/"model"\s*:\s*"([^"]+)"/);
  const model =
    modelMatch?.[1] ||
    process.env.ZG_COMPUTE_MODEL ||
    "qwen/qwen-2.5-7b-instruct";
  return { bearer, serviceUrl, model };
}

function writeGeneratedEnv({ bearer, serviceUrl, model }) {
  const outPath = join(ROOT, ".env.0g.compute.generated");
  const lines = [
    "# Auto-generated by npm run 0g:compute-setup — merge these into your real .env (never commit secrets)",
    `ZG_COMPUTE_SERVICE_URL=${serviceUrl ?? ""}`,
    `ZG_COMPUTE_API_SECRET=${bearer ?? ""}`,
    `ZG_COMPUTE_MODEL=${model}`,
    "",
    "# Legacy aliases (same values)",
    `OG_ROUTER_BASE_URL=${serviceUrl ? `${serviceUrl}/v1/proxy` : ""}`,
    `OG_ROUTER_API_KEY=${bearer ?? ""}`,
    `OG_ROUTER_MODEL=${model}`,
    "",
  ];
  writeFileSync(outPath, lines.join("\n"));
  console.log(`\n✓ Wrote ${outPath}`);
  console.log("  Add the ZG_COMPUTE_* (or OG_ROUTER_*) lines to your .env, then restart apps/api.\n");
}

try {
  bootstrapCliConfig();

  if (!onlySecret) {
    if (process.env.OG_COMPUTE_SKIP_DEPOSIT === "1") {
      console.log("Skipping deposit (OG_COMPUTE_SKIP_DEPOSIT=1)\n");
    } else {
      console.log(
        `Depositing ${depositAmount} OG into compute ledger (needs balance on 0G Chain + gas).`,
      );
      console.log(
        "If this fails with insufficient funds, get more OG from https://faucet.0g.ai — quickstart uses 3 OG minimum.\n",
      );
      runCli(["deposit", "--amount", depositAmount]);
    }

    if (process.env.OG_COMPUTE_SKIP_TRANSFER !== "1") {
      runCli([
        "transfer-fund",
        "--provider",
        provider,
        "--amount",
        transferAmount,
        "--service",
        "inference",
      ]);
    } else {
      console.log("Skipping transfer-fund (OG_COMPUTE_SKIP_TRANSFER=1)\n");
    }

    if (process.env.OG_COMPUTE_SKIP_ACK !== "1") {
      runCli(["inference", "acknowledge-provider", "--provider", provider]);
    } else {
      console.log("Skipping acknowledge-provider (OG_COMPUTE_SKIP_ACK=1)\n");
    }
  }

  const out = runCli(
    [
      "inference",
      "get-secret",
      "--provider",
      provider,
      "--duration",
      "0",
    ],
    { capture: true },
  );

  const parsed = parseGetSecretOutput(out);
  if (!parsed.bearer || !parsed.serviceUrl) {
    console.error(
      "\nCould not parse API URL / bearer token from CLI output. Copy values manually from the log above into .env:\n",
      "  ZG_COMPUTE_SERVICE_URL=<service host from curl>\n",
      "  ZG_COMPUTE_API_SECRET=<token after Bearer>\n",
    );
    process.exit(1);
  }

  writeGeneratedEnv(parsed);
} catch (e) {
  console.error(e instanceof Error ? e.message : e);
  console.error(
    "\nIf deposit failed: fund the wallet with more OG (quickstart uses 3 OG deposit + 1 OG transfer).",
  );
  console.error("Faucet: https://faucet.0g.ai\n");
  process.exit(1);
}
